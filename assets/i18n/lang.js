/* Language switch for the home sub-pages (EN / தமிழ் / සිංහල).
   Translations come from assets/i18n/subpages.js (generated by docs/i18n/build_subpages.mjs).
   The choice is shared with the home page through localStorage key "aama-lang". */
(function () {
  var D = window.AAMA_I18N || { ta: {}, si: {} };
  var KEY = 'aama-lang';
  var LABEL = { en: 'EN', ta: 'தமிழ்', si: 'සිංහල' };
  var norm = function (s) { return String(s || '').replace(/\s+/g, ' ').trim(); };
  var get = function () { try { return localStorage.getItem(KEY) || 'en'; } catch (e) { return 'en'; } };
  var put = function (l) { try { localStorage.setItem(KEY, l); } catch (e) {} };

  // Fonts and script-native type (DESIGN.md: The Script-Native Rule)
  var link = document.createElement('link'); link.rel = 'stylesheet';
  link.href = 'https://fonts.googleapis.com/css2?family=Noto+Sans+Tamil:wght@400;500;600&family=Noto+Serif+Tamil:wght@300;400&family=Noto+Sans+Sinhala:wght@400;500;600&family=Noto+Serif+Sinhala:wght@300;400&display=swap';
  document.head.appendChild(link);
  var css = document.createElement('style');
  css.textContent = [
    '.sub-lang{display:inline-flex;padding:3px;border-radius:9999px;background:color-mix(in oklch,var(--ink) 8%,transparent);gap:2px;margin-left:auto}',
    '.sub-lang button{border:0;background:transparent;color:var(--muted);min-height:30px;padding:0 10px;border-radius:9999px;font:500 12px var(--font-body);cursor:pointer;white-space:nowrap}',
    '.sub-lang button[lang="en"]{font:600 11px var(--font-mono);letter-spacing:.04em}',
    '.sub-lang button[lang="ta"]{font-family:"Noto Sans Tamil",var(--font-body)}',
    '.sub-lang button[lang="si"]{font-family:"Noto Sans Sinhala",var(--font-body)}',
    '.sub-lang button[aria-pressed="true"]{background:var(--ink);color:var(--canvas)}',
    '.sub-lang button:focus-visible{outline:2px solid currentColor;outline-offset:1px}',
    '.sub-nav .sub-lang + .sub-theme-toggle{margin-left:0}',
    '.sub-nav-title{margin-left:auto}',
    '@media (max-width:480px){.sub-nav-title{display:none}.sub-lang button{padding:0 7px}}',
    '@media (pointer:coarse){.sub-lang button{min-height:36px}}',
    'html[lang="ta"] body{font-family:"Noto Sans Tamil",var(--font-body)}',
    'html[lang="si"] body{font-family:"Noto Sans Sinhala",var(--font-body)}',
    'html[lang="ta"] .display{font-family:"Noto Serif Tamil",var(--font-display);letter-spacing:-.005em;line-height:1.22}',
    'html[lang="si"] .display{font-family:"Noto Serif Sinhala",var(--font-display);letter-spacing:-.005em;line-height:1.35}',
    'html[lang="ta"] .display-mega{font-size:clamp(28px,6.4vw,64px)}',
    'html[lang="si"] .display-mega{font-size:clamp(28px,6.4vw,64px)}',
    'html[lang="ta"] [class*="label"],html[lang="ta"] [class*="period"],html[lang="ta"] .sub-nav-back,html[lang="ta"] .sub-nav-title{font-family:"Noto Sans Tamil",var(--font-body);letter-spacing:.01em;text-transform:none}',
    'html[lang="si"] [class*="label"],html[lang="si"] [class*="period"],html[lang="si"] .sub-nav-back,html[lang="si"] .sub-nav-title{font-family:"Noto Sans Sinhala",var(--font-body);letter-spacing:.01em;text-transform:none}',
    'html[lang="ta"] p,html[lang="ta"] li{line-height:1.7}',
    'html[lang="si"] p,html[lang="si"] li{line-height:1.75}'
  ].join('\n');
  document.head.appendChild(css);

  // Record the English text once
  var nodes = [], attrs = [];
  var title = document.title, md = document.querySelector('meta[name="description"]'), mdEn = md ? md.content : '';
  var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null);
  while (walker.nextNode()) {
    var n = walker.currentNode, p = n.parentElement;
    if (!p || /^(SCRIPT|STYLE|NOSCRIPT)$/.test(p.tagName)) continue;
    var t = norm(n.data);
    if (t && D.ta[t]) nodes.push({ n: n, en: n.data, key: t });
  }
  ['aria-label', 'title', 'alt'].forEach(function (a) {
    document.querySelectorAll('[' + a + ']').forEach(function (el) { var t = norm(el.getAttribute(a)); if (D.ta[t]) attrs.push({ el: el, a: a, en: el.getAttribute(a), key: t }); });
  });

  function apply(l) {
    var map = l === 'en' ? null : D[l];
    nodes.forEach(function (x) { x.n.data = map && map[x.key] ? (/^\s/.test(x.en) ? ' ' : '') + map[x.key] + (/\s$/.test(x.en) ? ' ' : '') : x.en; });
    attrs.forEach(function (x) { x.el.setAttribute(x.a, map && map[x.key] ? map[x.key] : x.en); });
    document.title = map && map[norm(title)] ? map[norm(title)] : title;
    if (md) md.content = map && map[norm(mdEn)] ? map[norm(mdEn)] : mdEn;
    document.documentElement.lang = l;
    var bs = document.querySelectorAll('.sub-lang button');
    for (var i = 0; i < bs.length; i++) bs[i].setAttribute('aria-pressed', String(bs[i].lang === l));
  }

  // The switch, before the theme button
  var nav = document.querySelector('.sub-nav');
  if (nav) {
    var g = document.createElement('div'); g.className = 'sub-lang'; g.setAttribute('role', 'group'); g.setAttribute('aria-label', 'Language');
    ['en', 'ta', 'si'].forEach(function (l) {
      var b = document.createElement('button'); b.type = 'button'; b.lang = l; b.textContent = LABEL[l];
      b.addEventListener('click', function () { put(l); apply(l); });
      g.appendChild(b);
    });
    nav.insertBefore(g, nav.querySelector('.sub-theme-toggle'));
  }
  apply(D[get()] || get() === 'en' ? get() : 'en');
})();
