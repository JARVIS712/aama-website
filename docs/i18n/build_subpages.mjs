// Builds assets/i18n/subpages.js: for each home sub-page, the exact English text on the page
// mapped to Tamil and Sinhala from docs/i18n/aama-translations.csv.
// Run from the repo root with a local server on :8765:  node docs/i18n/build_subpages.mjs
import fs from 'node:fs'; import path from 'node:path'; import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PW || 'playwright');
const root = process.cwd();

// minimal CSV reader (quoted fields, CRLF)
function parseCSV(text) {
  const rows = []; let row = [], f = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true; else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n') { row.push(f); rows.push(row); row = []; f = ''; } else if (c !== '\r') f += c;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  const [h, ...rest] = rows; return rest.filter((r) => r.length > 1).map((r) => Object.fromEntries(h.map((k, i) => [k, r[i] || ''])));
}
const csv = parseCSV(fs.readFileSync(path.join(root, 'docs/i18n/aama-translations.csv'), 'utf8').replace(/^﻿/, ''));
const rows = csv.filter((r) => (r.surface === 'subpages' || r.surface === 'home' || r.surface === 'common') && r.tamil.trim());
const exact = new Map(); const templates = [];
for (const r of rows) {
  if (/\{[a-z]+\}/.test(r.english)) {
    const rx = new RegExp('^' + r.english.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\\\{[a-z]+\\\}/g, '(.+?)') + '$');
    templates.push({ rx, r });
  } else if (!exact.has(r.english)) exact.set(r.english, r);
}
const fill = (t, vals) => { let i = 0; return t.replace(/\{[a-z]+\}/g, () => vals[i++] ?? ''); };
const lookup = (s) => {
  const r = exact.get(s); if (r) return { ta: r.tamil.trim(), si: r.sinhala.trim() };
  for (const { rx, r: t } of templates) { const m = s.match(rx); if (m) return { ta: fill(t.tamil.trim(), m.slice(1)), si: fill(t.sinhala.trim(), m.slice(1)) }; }
  return null;
};

const pages = ['Predictive Analytics.html', 'Sentiment Mapping.html', 'Cyber Infrastructure.html', 'Roadmap.html'];
const collect = () => {
  const out = []; const push = (t, kind) => { t = (t || '').replace(/\s+/g, ' ').trim(); if (t && /[A-Za-z]{2,}/.test(t)) out.push([t, kind]); };
  push(document.title, 'title');
  const md = document.querySelector('meta[name="description"]'); if (md) push(md.content, 'meta');
  const tw = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, { acceptNode: (n) => n.parentElement && !['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(n.parentElement.tagName) ? 1 : 2 });
  const blocks = new Set();
  while (tw.nextNode()) { let el = tw.currentNode.parentElement; while (el && getComputedStyle(el).display === 'inline' && el.parentElement) el = el.parentElement; blocks.add(el); }
  const mixed = [];
  blocks.forEach((el) => {
    const kids = [...el.childNodes];
    const inlineOnly = kids.every((c) => c.nodeType === 3 || (c.nodeType === 1 && getComputedStyle(c).display === 'inline'));
    if (inlineOnly) {
      push(el.textContent, 'text');
      const hasText = kids.some((c) => c.nodeType === 3 && /[A-Za-z]{2,}/.test(c.textContent));
      const hasEl = kids.some((c) => c.nodeType === 1);
      if (hasText && hasEl) mixed.push(el.outerHTML.slice(0, 160));
    } else kids.forEach((c) => { if (c.nodeType === 3) push(c.textContent, 'text'); });
  });
  document.querySelectorAll('[aria-label]').forEach((e) => push(e.getAttribute('aria-label'), 'attr'));
  document.querySelectorAll('[title]').forEach((e) => push(e.getAttribute('title'), 'attr'));
  document.querySelectorAll('img[alt]').forEach((e) => push(e.getAttribute('alt'), 'attr'));
  return { out, mixed };
};
const b = await chromium.launch(); const p = await b.newPage();
await p.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.abort());
const map = { ta: {}, si: {} }; const missing = new Set(); const mixedAll = [];
for (const pg of pages) {
  await p.goto('http://localhost:8765/' + encodeURIComponent(pg)); await p.waitForTimeout(400);
  const { out, mixed } = await p.evaluate(collect); mixedAll.push(...mixed.map((m) => pg + ': ' + m));
  for (const [s] of out) {
    if (/^(AAMA|EN)$/.test(s)) continue;
    const t = lookup(s); if (!t) { missing.add(pg + ' | ' + s); continue; }
    map.ta[s] = t.ta; map.si[s] = t.si;
  }
}
await b.close();
fs.mkdirSync(path.join(root, 'assets/i18n'), { recursive: true });
fs.writeFileSync(path.join(root, 'assets/i18n/subpages.js'), '/* Generated by docs/i18n/build_subpages.mjs from docs/i18n/aama-translations.csv. Do not edit by hand. */\nwindow.AAMA_I18N = ' + JSON.stringify(map) + ';\n');
console.log('strings mapped:', Object.keys(map.ta).length);
if (mixedAll.length) console.log('blocks mixing text and links:\n  ' + mixedAll.join('\n  '));
if (missing.size) { console.log('no translation found:\n  ' + [...missing].join('\n  ')); process.exitCode = 1; }
